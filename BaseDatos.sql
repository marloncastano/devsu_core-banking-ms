-- Person: base entity with its own primary key.
CREATE TABLE IF NOT EXISTS person (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name           VARCHAR(100) NOT NULL,
	gender         VARCHAR(10)  NOT NULL,
	birth_date     DATE         NOT NULL,
	identification VARCHAR(20)  NOT NULL,
	address        VARCHAR(200) NOT NULL,
	phone          VARCHAR(15)  NOT NULL,
	created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT uk_person_identification UNIQUE (identification),
	CONSTRAINT ck_person_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER'))
);

-- Customer inherits from Person (JPA JOINED): its primary key is also a foreign key to person.
-- customer_id is the public identifier; the password is stored as a BCrypt hash.
CREATE TABLE IF NOT EXISTS customer (
	person_id   BIGINT       PRIMARY KEY,
	customer_id UUID         NOT NULL,
	password    VARCHAR(100) NOT NULL,
	active      BOOLEAN      NOT NULL DEFAULT TRUE,
	CONSTRAINT uk_customer_customer_id UNIQUE (customer_id),
	CONSTRAINT fk_customer_person FOREIGN KEY (person_id) REFERENCES person (id)
);


-- =====================================================================================================================
-- Core Banking - BaseDatos.sql
--
-- Schema of both microservice databases plus the data of the use cases of the specification.
-- One database per microservice: customers_db (customers-service) and accounts_db (accounts-service).
--
-- Usage (psql, connected to the "postgres" database):
--   docker compose up -d postgres
--   docker exec -i core-banking-postgres psql -U devsu -d postgres < BaseDatos.sql
--   or: psql -h localhost -p 5434 -U devsu -d postgres -f BaseDatos.sql
--
-- The script is idempotent: on an empty server it creates everything; on databases already migrated by the services
-- (Flyway) it only adds the missing data. The services also start on databases created by this script: Flyway takes
-- this schema as its baseline (spring.flyway.baseline-on-migrate).
--
-- In normal operation the schema is created by Flyway (src/main/resources/db/migration); this file consolidates it.
-- =====================================================================================================================


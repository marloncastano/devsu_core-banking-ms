-- Local read model of the customers owned by customers-service, kept up to date through RabbitMQ events.
CREATE TABLE IF NOT EXISTS customer_ref (
	customer_id   UUID         PRIMARY KEY,
	name          VARCHAR(100) NOT NULL,
	active        BOOLEAN      NOT NULL,
	updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
	-- Time of the last event applied, used to ignore events that arrive out of order.
	last_event_at TIMESTAMPTZ
);

-- Account numbers are assigned by the bank through this sequence (unique even under concurrency).
CREATE SEQUENCE IF NOT EXISTS account_number_seq START WITH 100000 MINVALUE 100000 NO CYCLE;

CREATE TABLE IF NOT EXISTS account (
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	account_number    VARCHAR(20)   NOT NULL,
	account_type      VARCHAR(10)   NOT NULL,
	initial_balance   NUMERIC(15,2) NOT NULL,
	available_balance NUMERIC(15,2) NOT NULL,
	active            BOOLEAN       NOT NULL DEFAULT TRUE,
	customer_id       UUID          NOT NULL,
	version           BIGINT        NOT NULL DEFAULT 0,
	created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
	updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
	CONSTRAINT uk_account_account_number UNIQUE (account_number),
	CONSTRAINT ck_account_type CHECK (account_type IN ('SAVINGS', 'CHECKING')),
	CONSTRAINT ck_account_initial_balance CHECK (initial_balance >= 0),
	-- Last line of defence for "Saldo no disponible": a balance can never go negative.
	CONSTRAINT ck_account_available_balance CHECK (available_balance >= 0),
	CONSTRAINT fk_account_customer FOREIGN KEY (customer_id) REFERENCES customer_ref (customer_id)
);

CREATE INDEX IF NOT EXISTS ix_account_customer_id ON account (customer_id);

-- Ledger of every movement. Rows are never updated: corrections are recorded as new movements.
CREATE TABLE IF NOT EXISTS movement (
	id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	movement_id     UUID          NOT NULL,
	account_id      BIGINT        NOT NULL,
	movement_type   VARCHAR(10)   NOT NULL,
	amount          NUMERIC(15,2) NOT NULL,
	balance         NUMERIC(15,2) NOT NULL,
	occurred_at     TIMESTAMPTZ   NOT NULL,
	created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
	-- Client-supplied Idempotency-Key, so a retried request is never applied twice.
	idempotency_key VARCHAR(100),
	CONSTRAINT uk_movement_movement_id UNIQUE (movement_id),
	CONSTRAINT uk_movement_idempotency_key UNIQUE (idempotency_key),
	CONSTRAINT fk_movement_account FOREIGN KEY (account_id) REFERENCES account (id),
	CONSTRAINT ck_movement_balance CHECK (balance >= 0),
	-- The sign of the amount defines the type: deposits are positive, withdrawals negative.
	CONSTRAINT ck_movement_type_sign CHECK (
		(movement_type = 'DEPOSIT' AND amount > 0) OR (movement_type = 'WITHDRAWAL' AND amount < 0))
);

-- Account statement queries filter by account and date range.
CREATE INDEX IF NOT EXISTS ix_movement_account_occurred_at ON movement (account_id, occurred_at);


CREATE TABLE person (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name           VARCHAR(100) NOT NULL,
	gender         VARCHAR(10)  NOT NULL,
	birth_date     DATE         NOT NULL,
	identification VARCHAR(20)  NOT NULL,
	address        VARCHAR(200) NOT NULL,
	phone          VARCHAR(15)  NOT NULL,
	created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT uk_person_identification UNIQUE (identification),
	CONSTRAINT ck_person_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER'))
);

-- JOINED inheritance: the customer primary key is also a foreign key to person.
-- Audit columns live only in person: a person row and its customer row form a single entity.
CREATE TABLE customer (
	person_id   BIGINT       PRIMARY KEY,
	customer_id UUID         NOT NULL,
	password    VARCHAR(100) NOT NULL,
	active      BOOLEAN      NOT NULL DEFAULT TRUE,
	CONSTRAINT uk_customer_customer_id UNIQUE (customer_id),
	CONSTRAINT fk_customer_person FOREIGN KEY (person_id) REFERENCES person (id)
);

-- Local read model of the customers owned by customers-service, kept up to date through events.
CREATE TABLE customer_ref (
	customer_id UUID         PRIMARY KEY,
	name        VARCHAR(100) NOT NULL,
	active      BOOLEAN      NOT NULL,
	updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Account numbers are assigned by the bank. A sequence never repeats values, even under concurrency.
CREATE SEQUENCE account_number_seq START WITH 100000 MINVALUE 100000 NO CYCLE;

CREATE TABLE account (
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	account_number    VARCHAR(20)   NOT NULL,
	account_type      VARCHAR(10)   NOT NULL,
	initial_balance   NUMERIC(15,2) NOT NULL,
	available_balance NUMERIC(15,2) NOT NULL,
	active            BOOLEAN       NOT NULL DEFAULT TRUE,
	customer_id       UUID          NOT NULL,
	version           BIGINT        NOT NULL DEFAULT 0,
	created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
	updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
	CONSTRAINT uk_account_account_number UNIQUE (account_number),
	CONSTRAINT ck_account_type CHECK (account_type IN ('SAVINGS', 'CHECKING')),
	CONSTRAINT ck_account_initial_balance CHECK (initial_balance >= 0),
	-- Last line of defence for "Saldo no disponible": a balance can never go negative.
	CONSTRAINT ck_account_available_balance CHECK (available_balance >= 0),
	CONSTRAINT fk_account_customer FOREIGN KEY (customer_id) REFERENCES customer_ref (customer_id)
);

CREATE INDEX ix_account_customer_id ON account (customer_id);

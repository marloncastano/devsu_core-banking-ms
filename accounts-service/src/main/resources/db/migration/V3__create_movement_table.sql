-- Ledger of every movement. Rows are never updated: corrections are recorded as new movements.
CREATE TABLE movement (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	movement_id   UUID          NOT NULL,
	account_id    BIGINT        NOT NULL,
	movement_type VARCHAR(10)   NOT NULL,
	amount        NUMERIC(15,2) NOT NULL,
	balance       NUMERIC(15,2) NOT NULL,
	occurred_at   TIMESTAMPTZ   NOT NULL,
	created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
	CONSTRAINT uk_movement_movement_id UNIQUE (movement_id),
	CONSTRAINT fk_movement_account FOREIGN KEY (account_id) REFERENCES account (id),
	CONSTRAINT ck_movement_balance CHECK (balance >= 0),
	-- The sign of the amount defines the type: deposits are positive, withdrawals negative.
	CONSTRAINT ck_movement_type_sign CHECK (
		(movement_type = 'DEPOSIT' AND amount > 0) OR (movement_type = 'WITHDRAWAL' AND amount < 0))
);

-- Account statement queries filter by account and date range.
CREATE INDEX ix_movement_account_occurred_at ON movement (account_id, occurred_at);
